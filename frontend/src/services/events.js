/**
 * Event service and centralized state for active event.
 */
import { api } from './api.js';

let currentEvent = null;
let eventsList = [];
const eventListeners = new Set();

export function subscribeEvents(listener) {
  eventListeners.add(listener);
  return () => eventListeners.delete(listener);
}

function notifyEvents() {
  for (const fn of eventListeners) {
    try {
      fn({ currentEvent, eventsList });
    } catch (e) {
      console.error('Event listener error', e);
    }
  }
}

export function getCurrentEvent() {
  return currentEvent;
}

export function getEventsList() {
  return eventsList;
}

export function setCurrentEvent(event) {
  currentEvent = event;
  if (event) {
    localStorage.setItem('last_event_id', event.id);
  } else {
    localStorage.removeItem('last_event_id');
  }
  notifyEvents();
}

export async function fetchEvents() {
  const previousEvents = JSON.stringify(eventsList);
  const previousCurrentEvent = JSON.stringify(currentEvent);
  const events = await api.get('/api/events');
  eventsList = events || [];

  const preferredId = localStorage.getItem('last_event_id') || currentEvent?.id;
  if (preferredId) {
    const found = eventsList.find(e => e.id === preferredId);
    if (found) {
      currentEvent = found;
    } else if (eventsList.length > 0) {
      currentEvent = eventsList[0];
    } else {
      currentEvent = null;
    }
  } else if (eventsList.length > 0) {
    currentEvent = eventsList[0];
  } else {
    currentEvent = null;
  }
  if (currentEvent) {
    localStorage.setItem('last_event_id', currentEvent.id);
  } else {
    localStorage.removeItem('last_event_id');
  }
  if (
    previousEvents !== JSON.stringify(eventsList)
    || previousCurrentEvent !== JSON.stringify(currentEvent)
  ) {
    notifyEvents();
  }
  return eventsList;
}

export async function selectEventById(id) {
  if (!id) return null;
  try {
    const event = await api.get(`/api/events/${id}`);
    currentEvent = event;
    localStorage.setItem('last_event_id', id);
    notifyEvents();
    return event;
  } catch {
    return null;
  }
}

export async function createNewEvent(payload) {
  const event = await api.post('/api/events', payload);
  await fetchEvents();
  setCurrentEvent(event);
  return event;
}

export async function updateEventDetails(id, payload) {
  const updated = await api.patch(`/api/events/${id}`, payload);
  currentEvent = updated;
  await fetchEvents();
  return updated;
}

export async function deleteEventById(id) {
  await api.delete(`/api/events/${id}`);
  await fetchEvents();
}

